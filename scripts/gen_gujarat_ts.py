#!/usr/bin/env python3
"""Convert .myneta-cache/gujarat/{gujarat,mp,rs}.json -> src/data/gujarat.ts, gujarat_mp.ts, gujarat_rs.ts"""
import json
import os
import re

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(BASE, ".myneta-cache", "gujarat")

DUPES = {'mandvi', 'kalol', 'jetpur', 'mangrol', 'mahuva'}

def slugify(name):
    s0 = name.lower()
    paren = re.search(r"\((.*?)\)", s0)
    s = re.sub(r"\(.*?\)", "", s0)
    base = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    if base in DUPES and paren:
        extra = re.sub(r"[^a-z0-9]+", "-", paren.group(1)).strip("-")
        return f"{base}-{extra}"
    return base

def ts_str(s):
    return (s or "").replace("\\", "\\\\").replace("'", "\\'")

def dist_disp(d):
    return (d or "").replace("DevbhoomiDwarka", "Devbhoomi Dwarka")

PARTY_MAP = {
    "BJP": ("BJP", "Bharatiya Janata Party"),
    "BHARATIYA JANATA PARTY": ("BJP", "Bharatiya Janata Party"),
    "INC": ("INC", "Indian National Congress"),
    "INDIAN NATIONAL CONGRESS": ("INC", "Indian National Congress"),
    "AAP": ("AAP", "Aam Aadmi Party"),
    "AAM AADMI PARTY": ("AAP", "Aam Aadmi Party"),
    "SP": ("SP", "Samajwadi Party"),
    "SAMAJWADI PARTY": ("SP", "Samajwadi Party"),
    "IND": ("IND", "Independent"),
    "INDEPENDENT": ("IND", "Independent"),
    "CPI(M)": ("CPI(M)", "Communist Party of India (Marxist)"),
    "BSP": ("BSP", "Bahujan Samaj Party"),
    "BAHUJAN SAMAJ PARTY": ("BSP", "Bahujan Samaj Party"),
    "NCP": ("NCP", "Nationalist Congress Party"),
    "SHIV SENA": ("SHS", "Shiv Sena"),
}

def party_of(short):
    pkey = (short or "").upper().strip()
    return PARTY_MAP.get(pkey, (short or "IND", short or "Independent"))

def bg_block(r, myneta_url, missing_note=""):
    assets = r.get("assets") or "Uplabdh nahi"
    liab = r.get("liabilities") or "Uplabdh nahi"
    return (
        "    background: {\n"
        f"      age: '{r.get('age','')}',\n"
        f"      education: '{ts_str(r.get('education',''))}',\n"
        f"      criminalCases: {r.get('criminal', 0)},\n"
        f"      assets: '{ts_str(assets)}',\n"
        f"      liabilities: '{ts_str(liab)}',\n"
        f"      mynetaUrl: '{myneta_url}',\n"
        f"      backgroundNote: '{ts_str(missing_note)}',\n"
        "    },"
    )

# ============ 1. MLAs ============
data = json.load(open(os.path.join(CACHE, "gujarat-fixed.json")))
print("MLA records:", len(data))
netas, consts = [], []
seen = set()
unknown_parties = set()
for r in sorted(data, key=lambda x: x["number"] or 999):
    slug = slugify(r["constituency"])
    if slug in seen:
        slug = f"{slug}-{r['number']}"
    seen.add(slug)
    short, full = party_of(r["party_short"])
    if (r["party_short"] or "").upper().strip() not in PARTY_MAP:
        unknown_parties.add(r["party_short"])
    res = "ST" if r["reservation"] == "ST" else ("SC" if r["reservation"] == "SC" else "\u2014")
    cname = r["constituency"]
    const_label = f"{cname} ({res})" if res != "\u2014" else cname
    nslug = slugify(r["name"])
    if nslug in seen:
        nslug = f"{nslug}-{r['number']}"
    seen.add(nslug)
    murl = f"https://myneta.info/Gujarat2022/candidate.php?candidate_id={r['candidate_id']}"
    if r.get("background_missing"):
        missing_note = "Halafnama ka record myneta.info par uplabdh nahi tha (Oct 2026); jald joda jayega."
        murl = ""
    else:
        missing_note = ""
    if r.get("bye_date"):
        tstart = r["bye_date"][:4]
        enote = f"{tstart} ke upchunav me {ts_str(cname)} se jeete."
    else:
        tstart = "2022"
        enote = f"2022 me {ts_str(cname)} se jeete."
    netas.append(
f"""  {{
    slug: '{nslug}',
    name: '{ts_str(r["name"])}',
    party: '{ts_str(full)}',
    partyShort: '{ts_str(short)}',
    post: 'MLA',
    state: 'Gujarat',
    constituency: '{ts_str(const_label)}',
    constituencySlug: '{slug}',
    tenures: [
      {{ post: 'MLA', constituency: '{ts_str(const_label)}', constituencySlug: '{slug}', party: '{ts_str(full)}', start: '{tstart}', end: '2027' }},
    ],
    works: [],
    fund: {{
      scheme: 'MLALADS',
      allocated: null, utilized: null, utilizationPct: null,
      note: 'Gujarat me MLA fund ka record online uplabdh nahi hai. RTI se data manga jayega.',
    }},
{bg_block(r, murl, missing_note)}
    electionNote: '{enote}',
  }},""")
    consts.append(
f"""  {{ slug: '{slug}', name: '{ts_str(cname)}', type: 'Vidhan Sabha', number: {r["number"] or "null"}, district: '{ts_str(dist_disp(r["district"]))}', reservation: '{res}' }},""")

out = """// AUTO-GENERATED by scripts/gen_gujarat_ts.py from myneta.info (Gujarat2022)
// 182 MLAs. Background data = ECI affidavit via myneta.info.
import type { Neta, Constituency } from './pilot';

export const gujNetas: Neta[] = [
""" + "\n".join(netas) + "\n];\n\nexport const gujConstituencies: Constituency[] = [\n" + "\n".join(consts) + "\n];\n"
open(os.path.join(BASE, "src", "data", "gujarat.ts"), "w").write(out)
print("wrote gujarat.ts:", len(netas), "netas")
print("unknown parties:", sorted(unknown_parties))

# ============ 2. Lok Sabha MPs ============
mpdata = json.load(open(os.path.join(CACHE, "mp.json")))
print("MP records:", len(mpdata))
mnetas, mconsts = [], []
seen = set()
for r in mpdata:
    craw = r["constituency_raw"]
    res = "SC" if "(SC)" in craw else ("ST" if "(ST)" in craw else "\u2014")
    pc_raw = re.sub(r"\s*\(S[CT]\)\s*", "", craw).strip().title()
    cslug = slugify(pc_raw) + "-lok-sabha"
    if cslug in seen:
        cslug = cslug + "-2"
    seen.add(cslug)
    short, full = party_of(r["party_short"])
    const_label = f"{pc_raw} (Lok Sabha)"
    nslug = slugify(r["name"])
    if nslug in seen:
        nslug = nslug + "-mp"
    seen.add(nslug)
    murl = f"https://myneta.info/LokSabha2024/candidate.php?candidate_id={r['candidate_id']}"
    mnetas.append(
f"""  {{
    slug: '{nslug}',
    name: '{ts_str(r["name"])}',
    party: '{ts_str(full)}',
    partyShort: '{ts_str(short)}',
    post: 'MP',
    house: 'Lok Sabha',
    state: 'Gujarat',
    constituency: '{ts_str(const_label)}',
    constituencySlug: '{cslug}',
    tenures: [
      {{ post: 'MP', constituency: '{ts_str(const_label)}', constituencySlug: '{cslug}', party: '{ts_str(full)}', start: '2024', end: '2029' }},
    ],
    works: [],
    fund: {{
      scheme: 'MPLADS',
      allocated: null, utilized: null, utilizationPct: null,
      note: 'MPLADS fund ka record e-SAKSHI portal par uplabdh hai; jald joda jayega.',
    }},
{bg_block(r, murl)}
    electionNote: '2024 me {ts_str(pc_raw)} Lok Sabha se jeete.',
  }},""")
    mconsts.append(
f"""  {{ slug: '{cslug}', name: '{ts_str(pc_raw)}', type: 'Lok Sabha', number: null, district: '', reservation: '{res}' }},""")

out = """// AUTO-GENERATED by scripts/gen_gujarat_ts.py from myneta.info (LokSabha2024)
// 26 Gujarat MPs. Background data = ECI affidavit via myneta.info.
import type { Neta, Constituency } from './pilot';

export const gujMpNetas: Neta[] = [
""" + "\n".join(mnetas) + "\n];\n\nexport const gujMpConstituencies: Constituency[] = [\n" + "\n".join(mconsts) + "\n];\n"
open(os.path.join(BASE, "src", "data", "gujarat_mp.ts"), "w").write(out)
print("wrote gujarat_mp.ts:", len(mnetas), "MPs")

# ============ 3. Rajya Sabha MPs ============
rsdata = json.load(open(os.path.join(CACHE, "rs.json")))
print("RS records:", len(rsdata))
rnetas = []
seen = set()
for r in rsdata:
    short, full = party_of(r["party_short"])
    nslug = slugify(r["name"])
    if nslug in seen:
        nslug = nslug + "-rs"
    seen.add(nslug)
    edu = r["education_cat"] or r["education_detail"] or ""
    bg = {
        "age": r.get("age", ""), "education": edu, "criminal": r.get("criminal", 0),
        "assets": r.get("assets") or "Uplabdh nahi", "liabilities": r.get("liabilities") or "Uplabdh nahi",
    }
    rnetas.append(
f"""  {{
    slug: '{nslug}',
    name: '{ts_str(r["name"])}',
    party: '{ts_str(full)}',
    partyShort: '{ts_str(short)}',
    post: 'MP',
    house: 'Rajya Sabha',
    state: 'Gujarat',
    constituency: 'Gujarat (Rajya Sabha)',
    constituencySlug: 'gujarat-rajya-sabha',
    tenures: [
      {{ post: 'MP', constituency: 'Gujarat (Rajya Sabha)', constituencySlug: 'gujarat-rajya-sabha', party: '{ts_str(full)}', start: '{r["term_start"]}', end: '{r["term_end"]}' }},
    ],
    works: [],
    fund: null,
{bg_block(bg, r["myneta_url"])}
    electionNote: '{r["term_start"]} me Gujarat se Rajya Sabha ke liye chune gaye (karyakal {r["term_start"]}–{r["term_end"]}).',
  }},""")

out = """// AUTO-GENERATED by scripts/gen_gujarat_ts.py from myneta.info (rajsab09aff)
// 11 Gujarat Rajya Sabha MPs (all verified Oct 2026). Background data = ECI affidavit via myneta.info.
import type { Neta } from './pilot';

export const gujRsNetas: Neta[] = [
""" + "\n".join(rnetas) + "\n];\n"
open(os.path.join(BASE, "src", "data", "gujarat_rs.ts"), "w").write(out)
print("wrote gujarat_rs.ts:", len(rnetas), "RS MPs")
