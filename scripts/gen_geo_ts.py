#!/usr/bin/env python3
"""Generate src/data/geo.ts: AC number -> talukas, district -> talukas, AC -> PC slug.
Sources: CEO Maharashtra delimitation notification (TABLE-A/B) + verified manual
additions for Mumbai Suburban (3 talukas) and Pune City."""
import json
import os
import re
import unicodedata

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(BASE, ".myneta-cache")
g = json.load(open(os.path.join(CACHE, "geo.json"), encoding="utf-8"))

# delimitation district name -> site (myneta) district name
DIST_FIX = {"Amravati": "Amaravati", "Nandurbar": "Nandurbar".replace("Nandurbar", "Nandurabar")}
# Palghar district was carved out of Thane in 2014 (after 2008 delimitation)
PALGHAR_ACS = {128, 129, 130, 131, 132, 133}

# Mumbai Suburban: 3 official talukas (mumbaisuburban.gov.in).
# Seat mapping verified via revenue records / ward mapping (2026-10-12):
# - Bandra -> Andheri taluka (ready reckoner: "TALUKA ANDHERI, VILLAGE BANDRA")
# - Kalina/Santacruz East -> Andheri taluka (prop records)
# - Jogeshwari East -> Andheri taluka (K/East ward)
# - Chandivali (L ward: Sakinaka/Chandivali) -> Kurla block
MUMBAI_TALUKA = {}
for n in [158, 164, 165, 166, 167, 175, 176, 177]:
    MUMBAI_TALUKA[n] = ["Andheri"]
for n in [152, 153, 154, 159, 160, 161, 162, 163]:
    MUMBAI_TALUKA[n] = ["Borivali"]
for n in [155, 156, 157, 168, 169, 170, 171, 172, 173, 174]:
    MUMBAI_TALUKA[n] = ["Kurla"]
# Pune city seats -> Pune City taluka (official taluka of Pune district)
PUNE_CITY = {209, 210, 212, 214, 215}
# Taluka's home district when an AC from another district touches it
# (Wada taluka is in Palghar; Shahapur AC of Thane covers Wada Tehsil (Part))
TALUKA_HOME = {"Wada": "Palghar"}


def slugify(s: str) -> str:
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    s = re.sub(r"[^a-zA-Z0-9]+", "-", s).strip("-").lower()
    return s


ac_talukas: dict[int, list[str]] = {}
ac_district: dict[int, str] = {}
for num_s, c in g["constituencies"].items():
    num = int(num_s)
    d = DIST_FIX.get(c["district"], c["district"])
    if num in PALGHAR_ACS:
        d = "Palghar"
    ac_district[num] = d
    if num in MUMBAI_TALUKA:
        ac_talukas[num] = MUMBAI_TALUKA[num]
    elif num in PUNE_CITY:
        ac_talukas[num] = ["Pune City"]
    else:
        ac_talukas[num] = c["talukas"]

district_talukas: dict[str, list[str]] = {}
for num, d in ac_district.items():
    for t in ac_talukas.get(num, []):
        hd = TALUKA_HOME.get(t, d)
        district_talukas.setdefault(hd, [])
        if t not in district_talukas[hd]:
            district_talukas[hd].append(t)
for d in district_talukas:
    district_talukas[d].sort()

# AC -> PC slug (for district page -> MP links)
ac_to_pc = {}
for num_s, pc in g["ac_to_pc"].items():
    num = int(num_s)
    pc_clean = re.sub(r"\s*\((ST|SC)\)\s*$", "", pc).strip()
    pc_clean = pc_clean.replace(" - ", "-").replace(" – ", "-")
    ac_to_pc[num] = slugify(pc_clean) + "-lok-sabha"

out = []
out.append("// AUTO-GENERATED by scripts/gen_geo_ts.py — do not edit by hand.")
out.append("// Sources: CEO Maharashtra delimitation notification 2008 (TABLE-A/B);")
out.append("// Mumbai Suburban taluka mapping verified 2026-10-12 (revenue records).")
out.append("")
out.append("export const acTalukas: Record<number, string[]> = {")
for num in sorted(ac_talukas):
    ts = ", ".join(f'"{t}"' for t in ac_talukas[num])
    out.append(f"  {num}: [{ts}],")
out.append("};")
out.append("")
out.append("export const acDistrict: Record<number, string> = {")
for num in sorted(ac_district):
    out.append(f'  {num}: "{ac_district[num]}",')
out.append("};")
out.append("")
out.append("export const districtTalukas: Record<string, string[]> = {")
for d in sorted(district_talukas):
    ts = ", ".join(f'"{t}"' for t in district_talukas[d])
    out.append(f'  "{d}": [{ts}],')
out.append("};")
out.append("")
out.append("export const acToPcSlug: Record<number, string> = {")
for num in sorted(ac_to_pc):
    out.append(f'  {num}: "{ac_to_pc[num]}",')
out.append("};")
out.append("")
out.append("export function slugify(s: string): string {")
out.append("  return s.normalize('NFKD').replace(/[\\u0300-\\u036f]/g, '')")
out.append("    .replace(/[^a-zA-Z0-9]+/g, '-').replace(/^-+|-+$/g, '').toLowerCase();")
out.append("}")
out.append("")
out.append("// Sirf tab jab taluka apne AC ke jile se alag jile me ho (Wada -> Palghar)")
out.append('export const talukaHomeOverride: Record<string, string> = {"Wada": "Palghar"};')
out.append("")
out.append("export const districtSlug = (d: string) => slugify(d);")
out.append("export const talukaPath = (district: string, taluka: string) =>")
out.append("  `/taluka/${slugify(district)}/${slugify(taluka)}`;")
out.append("// AC page se link: taluka apne home jile ke path par hota hai")
out.append("export const talukaLink = (district: string, taluka: string) =>")
out.append("  talukaPath(talukaHomeOverride[taluka] ?? district, taluka);")
out.append("export const districtPath = (district: string) => `/jila/${slugify(district)}`;")
out.append("")

open(os.path.join(BASE, "src/data/geo.ts"), "w", encoding="utf-8").write("\n".join(out))
n_tal = sum(len(v) for v in district_talukas.values())
print(f"geo.ts written: {len(ac_talukas)} ACs, {len(district_talukas)} districts, {n_tal} taluka entries, {len(ac_to_pc)} AC->PC")
# sanity: every district in maharashtra.ts covered?
mha = open(os.path.join(BASE, "src/data/maharashtra.ts"), encoding="utf-8").read()
mha_d = set(re.findall(r"district: '([^']+)'", mha)) | {"Palghar"}
missing = [d for d in mha_d if d not in district_talukas]
print("districts missing talukas:", missing)
