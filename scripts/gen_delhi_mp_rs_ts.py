#!/usr/bin/env python3
"""Convert .myneta-cache/delhi/{mp,rs}.json -> src/data/delhi_mp.ts, src/data/delhi_rs.ts
Adapted from scripts/gen_up_mp_rs_ts.py for Delhi."""
import glob
import json
import os
import re

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(BASE, ".myneta-cache", "delhi")
DATA = os.path.join(BASE, "src", "data")


def slugify(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def ts_str(s):
    return (s or "").replace("\\", "\\\\").replace("'", "\\'")


PARTY_MAP = {
    "BJP": ("BJP", "Bharatiya Janata Party"),
    "BHARATIYA JANATA PARTY": ("BJP", "Bharatiya Janata Party"),
    "AAP": ("AAP", "Aam Aadmi Party"),
    "AAM AADMI PARTY": ("AAP", "Aam Aadmi Party"),
    "INC": ("INC", "Indian National Congress"),
    "INDIAN NATIONAL CONGRESS": ("INC", "Indian National Congress"),
    "IND": ("IND", "Independent"),
    "INDEPENDENT": ("IND", "Independent"),
}


def party_of(short):
    pkey = (short or "").upper().strip()
    return PARTY_MAP.get(pkey, (short or "IND", short or "Independent"))


def bg_block(r, myneta_url, missing_note=""):
    assets = r.get("assets") or "Uplabdh nahi"
    liab = r.get("liabilities") or "Uplabdh nahi"
    return (
        "    background: {\n"
        f"      age: '{r.get('age','')}',\n"
        f"      education: '{ts_str(r.get('education',''))}',\n"
        f"      criminalCases: {r.get('criminal', 0)},\n"
        f"      assets: '{ts_str(assets)}',\n"
        f"      liabilities: '{ts_str(liab)}',\n"
        f"      mynetaUrl: '{myneta_url}',\n"
        f"      backgroundNote: '{ts_str(missing_note)}',\n"
        "    },"
    )


# ---- existing neta slugs across src/data/*.ts (collision guard) ----
existing_slugs = set()
for f in glob.glob(os.path.join(DATA, "*.ts")):
    if os.path.basename(f) in ("delhi_mp.ts", "delhi_rs.ts", "delhi.ts"):
        continue
    try:
        txt = open(f, encoding="utf-8", errors="replace").read()
    except Exception:
        continue
    for m in re.finditer(r"slug:\s*'([^']+)'", txt):
        existing_slugs.add(m.group(1))
print("existing slugs in src/data/*.ts:", len(existing_slugs))


def unique_nslug(base, seen, suffix):
    nslug = base
    if nslug in existing_slugs or nslug in seen:
        nslug = base + suffix
    k = 2
    while nslug in existing_slugs or nslug in seen:
        nslug = f"{base}{suffix}-{k}"
        k += 1
    return nslug


# ============ 1. Lok Sabha MPs ============
mpdata = json.load(open(os.path.join(CACHE, "mp.json")))
print("MP records:", len(mpdata))
mnetas, mconsts = [], []
seen_slugs, seen_cslugs = set(), set()
collisions = []
unknown_parties = set()
for r in mpdata:
    craw = r["constituency_raw"]
    res = "SC" if "(SC)" in craw else ("ST" if "(ST)" in craw else "—")
    pc_raw = re.sub(r"\s*\(S[CT]\)\s*", "", craw).strip().title()
    cslug = slugify(pc_raw) + "-lok-sabha"
    if cslug in seen_cslugs or cslug in existing_slugs:
        cslug = cslug + "-delhi"
    seen_cslugs.add(cslug)
    short, full = party_of(r["party_short"])
    if (r["party_short"] or "").upper().strip() not in PARTY_MAP:
        unknown_parties.add(r["party_short"])
    const_label = f"{pc_raw} (Lok Sabha)"
    nslug = unique_nslug(slugify(r["name"]), seen_slugs, "-mp")
    if nslug != slugify(r["name"]):
        collisions.append(("mp", r["name"], nslug))
    seen_slugs.add(nslug)
    murl = f"https://myneta.info/LokSabha2024/candidate.php?candidate_id={r['candidate_id']}"
    mnetas.append(
f"""  {{
    slug: '{nslug}',
    name: '{ts_str(r["name"])}',
    party: '{ts_str(full)}',
    partyShort: '{ts_str(short)}',
    post: 'MP',
    house: 'Lok Sabha',
    state: 'Delhi',
    constituency: '{ts_str(const_label)}',
    constituencySlug: '{cslug}',
    tenures: [
      {{ post: 'MP', constituency: '{ts_str(const_label)}', constituencySlug: '{cslug}', party: '{ts_str(full)}', start: '2024', end: '2029' }},
    ],
    works: [],
    fund: {{
      scheme: 'MPLADS',
      allocated: null, utilized: null, utilizationPct: null,
      note: 'MPLADS fund ka record e-SAKSHI portal par uplabdh hai; jald joda jayega.',
    }},
{bg_block(r, murl)}
    electionNote: '2024 me {ts_str(pc_raw)} Lok Sabha se jeete.',
  }},""")
    mconsts.append(
f"""  {{ slug: '{cslug}', name: '{ts_str(pc_raw)}', type: 'Lok Sabha', number: null, district: '', reservation: '{res}', state: 'Delhi' }},""")

out = f"""// AUTO-GENERATED by scripts/gen_delhi_mp_rs_ts.py from myneta.info (LokSabha2024)
// {len(mnetas)} Delhi MPs. Background data = ECI affidavit via myneta.info.
import type {{ Neta, Constituency }} from './pilot';

export const delhiMpNetas: Neta[] = [
""" + "\n".join(mnetas) + "\n];\n\nexport const delhiMpConstituencies: Constituency[] = [\n" + "\n".join(mconsts) + "\n];\n"
open(os.path.join(DATA, "delhi_mp.ts"), "w").write(out)
print("wrote delhi_mp.ts:", len(mnetas), "MPs")
print("unknown parties (MP):", sorted(unknown_parties))

# ============ 2. Rajya Sabha MPs ============
rsdata = json.load(open(os.path.join(CACHE, "rs.json")))
print("RS records:", len(rsdata))
rnetas = []
seen_slugs = set()
for r in rsdata:
    short, full = party_of(r["party_short"])
    nslug = unique_nslug(slugify(r["name"]), seen_slugs, "-rs")
    if nslug != slugify(r["name"]):
        collisions.append(("rs", r["name"], nslug))
    seen_slugs.add(nslug)
    edu = r.get("education") or ""
    bg = {
        "age": r.get("age", ""), "education": edu, "criminal": r.get("criminal", 0),
        "assets": r.get("assets") or "Uplabdh nahi", "liabilities": r.get("liabilities") or "Uplabdh nahi",
    }
    # Swati Maliwal: AAP se chuni gayin, Apr 2026 me BJP me vilay (RS Chairman ne sweekar kiya; AAP ne ayogyata-yachika di hai)
    if r["candidate_id"] == "1030":
        enote = "Jan 2024 me Delhi se Rajya Sabha ke liye nirvirodh chuni gayin (karyakal 2024-2030). AAP se chuni gayin thi; April 2026 me 7 AAP Rajya Sabha saansadon ke BJP me vilay me shaamil hui (Rajya Sabha Chairman ne vilay sweekar kiya; AAP ne ayogyata ki yachika di hai) — vartamaan me BJP saansad ke roop me baithi hain."
    else:
        enote = f"{r['term_start']} me Delhi se Rajya Sabha ke liye nirvirodh chune gaye (karyakal {r['term_start']}–{r['term_end']})."
    rnetas.append(
f"""  {{
    slug: '{nslug}',
    name: '{ts_str(r["name"])}',
    party: '{ts_str(full)}',
    partyShort: '{ts_str(short)}',
    post: 'MP',
    house: 'Rajya Sabha',
    state: 'Delhi',
    constituency: 'Delhi (Rajya Sabha)',
    constituencySlug: 'delhi-rajya-sabha',
    tenures: [
      {{ post: 'MP', constituency: 'Delhi (Rajya Sabha)', constituencySlug: 'delhi-rajya-sabha', party: '{ts_str(full)}', start: '{r["term_start"]}', end: '{r["term_end"]}' }},
    ],
    works: [],
    fund: null,
{bg_block(bg, r["myneta_url"])}
    electionNote: '{ts_str(enote)}',
  }},""")

out = f"""// AUTO-GENERATED by scripts/gen_delhi_mp_rs_ts.py from myneta.info (rajsab09aff)
// {len(rnetas)} Delhi Rajya Sabha MPs (verified Oct 2026: 2024-2030 batch; Maliwal BJP vilay Apr 2026).
// Background data = ECI affidavit via myneta.info.
import type {{ Neta }} from './pilot';

export const delhiRsNetas: Neta[] = [
""" + "\n".join(rnetas) + "\n];\n\nexport const delhiRsConstituencies = [\n  { slug: 'delhi-rajya-sabha', name: 'Delhi (Rajya Sabha)', type: 'Rajya Sabha' as const, number: null, district: 'Delhi', reservation: '', state: 'Delhi' },\n];\n"
open(os.path.join(DATA, "delhi_rs.ts"), "w").write(out)
print("wrote delhi_rs.ts:", len(rnetas), "RS MPs")

print("slug collisions resolved:", len(collisions))
for c in collisions:
    print("  COLLISION:", c)
